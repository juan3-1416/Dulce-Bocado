-- microservicios sales, order, customer y security (noviembre de 2026).

CREATE ROLE dulce_sales_user LOGIN PASSWORD 'bi_demo_sales_2026';
CREATE ROLE dulce_orders_user LOGIN PASSWORD 'bi_demo_orders_2026';
CREATE ROLE dulce_customers_user LOGIN PASSWORD 'bi_demo_customers_2026';
CREATE ROLE dulce_security_user LOGIN PASSWORD 'bi_demo_security_2026';

CREATE DATABASE dulce_sales OWNER dulce_sales_user;
CREATE DATABASE dulce_orders OWNER dulce_orders_user;
CREATE DATABASE dulce_customers OWNER dulce_customers_user;
CREATE DATABASE dulce_security OWNER dulce_security_user;

\connect dulce_sales
CREATE TABLE venta (
    id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT,
    nombre_cliente_ocasional VARCHAR(150),
    id_usuario BIGINT NOT NULL,
    fecha_venta TIMESTAMPTZ NOT NULL,
    total NUMERIC(12,2) NOT NULL CHECK (total >= 0),
    moneda CHAR(3) NOT NULL DEFAULT 'BOB',
    estado VARCHAR(24) NOT NULL CHECK (estado IN ('BORRADOR', 'CANCELADA')),
    id_usuario_cancelacion BIGINT,
    motivo_cancelacion VARCHAR(500),
    fecha_cancelacion TIMESTAMPTZ,
    CHECK (
      (id_cliente IS NOT NULL AND nombre_cliente_ocasional IS NULL)
      OR (id_cliente IS NULL AND NULLIF(BTRIM(nombre_cliente_ocasional), '') IS NOT NULL)
    ),
    CHECK (
      (estado = 'BORRADOR' AND id_usuario_cancelacion IS NULL
       AND motivo_cancelacion IS NULL AND fecha_cancelacion IS NULL)
      OR (estado = 'CANCELADA' AND id_usuario_cancelacion IS NOT NULL
       AND NULLIF(BTRIM(motivo_cancelacion), '') IS NOT NULL
       AND fecha_cancelacion IS NOT NULL)
    )
);
CREATE TABLE detalle_venta (
    id_detalle_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta BIGINT NOT NULL REFERENCES venta(id_venta),
    presentacion_id BIGINT NOT NULL,
    nombre_presentacion_snapshot VARCHAR(200) NOT NULL,
    precio_unitario_snapshot NUMERIC(12,2) NOT NULL CHECK (precio_unitario_snapshot >= 0),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    costo_personalizacion NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (costo_personalizacion >= 0),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0)
);
GRANT USAGE ON SCHEMA public TO dulce_sales_user;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO dulce_sales_user;

\connect dulce_orders
CREATE TABLE pedido (
    id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT,
    nombre_cliente_snapshot VARCHAR(200),
    nombre_cliente_ocasional VARCHAR(150),
    id_usuario BIGINT NOT NULL,
    fecha_pedido TIMESTAMP NOT NULL,
    fecha_entrega DATE NOT NULL,
    hora_entrega TIME NOT NULL,
    total NUMERIC(12,2) NOT NULL CHECK (total >= 0),
    moneda CHAR(3) NOT NULL DEFAULT 'BOB',
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('PROGRAMADO', 'EN_PROCESO', 'ENTREGADO', 'CANCELADO')),
    id_usuario_entrega BIGINT,
    fecha_entrega_efectiva TIMESTAMP,
    id_usuario_cancelacion BIGINT,
    motivo_cancelacion VARCHAR(500),
    fecha_cancelacion TIMESTAMP,
    CHECK (
       (id_cliente IS NOT NULL AND nombre_cliente_snapshot IS NOT NULL
        AND nombre_cliente_ocasional IS NULL)
       OR (id_cliente IS NULL AND nombre_cliente_snapshot IS NULL
           AND nombre_cliente_ocasional IS NOT NULL)
    ),
    CHECK (
      (estado IN ('PROGRAMADO', 'EN_PROCESO')
       AND id_usuario_entrega IS NULL AND fecha_entrega_efectiva IS NULL
       AND id_usuario_cancelacion IS NULL AND motivo_cancelacion IS NULL
       AND fecha_cancelacion IS NULL)
      OR (estado = 'ENTREGADO' AND id_usuario_entrega IS NOT NULL
          AND fecha_entrega_efectiva IS NOT NULL
          AND id_usuario_cancelacion IS NULL AND motivo_cancelacion IS NULL
          AND fecha_cancelacion IS NULL)
      OR (estado = 'CANCELADO' AND id_usuario_entrega IS NULL
          AND fecha_entrega_efectiva IS NULL AND id_usuario_cancelacion IS NOT NULL
          AND motivo_cancelacion IS NOT NULL AND fecha_cancelacion IS NOT NULL)
    )
);
CREATE TABLE detalle_pedido (
    id_detalle_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES pedido(id_pedido),
    presentacion_id BIGINT NOT NULL,
    nombre_producto_snapshot VARCHAR(150) NOT NULL,
    nombre_presentacion_snapshot VARCHAR(200) NOT NULL,
    precio_unitario_snapshot NUMERIC(12,2) NOT NULL CHECK (precio_unitario_snapshot >= 0),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    costo_personalizacion NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (costo_personalizacion >= 0),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0)
);
