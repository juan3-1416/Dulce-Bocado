-- Data Warehouse de Dulce Bocado: modelo fisico inicial.
-- Fuentes verificadas en las migraciones de catalog, customers, sales, orders
-- y security (microservicios del ZIP compartido, noviembre de 2026).
-- SOLO se ejecuta en la base nueva dulce_dw; nunca en las bases OLTP.

CREATE SCHEMA IF NOT EXISTS dw;
CREATE SCHEMA IF NOT EXISTS staging;

CREATE TABLE IF NOT EXISTS dw.dim_tiempo (
    sk_fecha INTEGER PRIMARY KEY,                 -- AAAAMMDD
    fecha DATE NOT NULL UNIQUE,
    dia SMALLINT NOT NULL CHECK (dia BETWEEN 1 AND 31),
    mes SMALLINT NOT NULL CHECK (mes BETWEEN 1 AND 12),
    trimestre SMALLINT NOT NULL CHECK (trimestre BETWEEN 1 AND 4),
    anio SMALLINT NOT NULL,
    nombre_mes VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_producto (
    sk_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presentacion_id_origen BIGINT UNIQUE,
    id_producto_origen BIGINT,
    id_categoria_origen BIGINT,
    nombre_categoria VARCHAR(100) NOT NULL,
    nombre_producto VARCHAR(150) NOT NULL,
    nombre_presentacion VARCHAR(200) NOT NULL,
    moneda CHAR(3),
    disponible BOOLEAN,
    permite_personalizacion BOOLEAN,
    fecha_actualizacion_dw TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS dw.dim_cliente (
    sk_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente_origen BIGINT UNIQUE,
    nombre_cliente VARCHAR(200) NOT NULL,
    es_ocasional BOOLEAN NOT NULL DEFAULT FALSE,
    estado BOOLEAN,
    fecha_actualizacion_dw TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS dw.dim_usuario (
    sk_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_origen BIGINT UNIQUE,
    nombre_usuario VARCHAR(120) NOT NULL,
    login_usuario VARCHAR(80),
    activo BOOLEAN,
    fecha_actualizacion_dw TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Miembros desconocidos: permiten integrar referencias externas ausentes
-- o clientes ocasionales sin perder lineas de venta o pedido.
INSERT INTO dw.dim_producto (
    sk_producto, nombre_categoria, nombre_producto, nombre_presentacion
) VALUES (0, 'Sin categoria', 'Producto desconocido', 'Presentacion desconocida')
ON CONFLICT (sk_producto) DO NOTHING;

INSERT INTO dw.dim_cliente (
    sk_cliente, nombre_cliente, es_ocasional
) VALUES (0, 'Ocasional o no identificado', TRUE)
ON CONFLICT (sk_cliente) DO NOTHING;

INSERT INTO dw.dim_usuario (
    sk_usuario, nombre_usuario
) VALUES (0, 'Usuario desconocido')
ON CONFLICT (sk_usuario) DO NOTHING;

-- Una fila por detalle_venta del servicio dulce_sales.
CREATE TABLE IF NOT EXISTS dw.fact_ventas (
    sk_fact_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_detalle_venta_origen BIGINT NOT NULL UNIQUE,
    id_venta_origen BIGINT NOT NULL,
    sk_fecha_venta INTEGER NOT NULL REFERENCES dw.dim_tiempo(sk_fecha),
    sk_producto BIGINT NOT NULL REFERENCES dw.dim_producto(sk_producto),
    sk_cliente BIGINT NOT NULL REFERENCES dw.dim_cliente(sk_cliente),
    sk_usuario BIGINT NOT NULL REFERENCES dw.dim_usuario(sk_usuario),
    fecha_venta_origen TIMESTAMPTZ NOT NULL,
    nombre_presentacion_snapshot VARCHAR(200),
    nombre_cliente_ocasional VARCHAR(150),
    estado_venta VARCHAR(24) NOT NULL,
    moneda CHAR(3) NOT NULL DEFAULT 'BOB',
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario_snapshot NUMERIC(12,2) NOT NULL CHECK (precio_unitario_snapshot >= 0),
    costo_personalizacion NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (costo_personalizacion >= 0),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    fecha_carga_dw TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Una fila por detalle_pedido del servicio dulce_orders.
-- dim_tiempo se utiliza tres veces para las fechas de este proceso.
CREATE TABLE IF NOT EXISTS dw.fact_pedidos (
    sk_fact_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_detalle_pedido_origen BIGINT NOT NULL UNIQUE,
    id_pedido_origen BIGINT NOT NULL,
    sk_fecha_pedido INTEGER NOT NULL REFERENCES dw.dim_tiempo(sk_fecha),
    sk_fecha_programada INTEGER NOT NULL REFERENCES dw.dim_tiempo(sk_fecha),
    sk_fecha_entrega_real INTEGER REFERENCES dw.dim_tiempo(sk_fecha),
    sk_producto BIGINT NOT NULL REFERENCES dw.dim_producto(sk_producto),
    sk_cliente BIGINT NOT NULL REFERENCES dw.dim_cliente(sk_cliente),
    sk_usuario BIGINT NOT NULL REFERENCES dw.dim_usuario(sk_usuario),
    fecha_pedido_origen TIMESTAMP NOT NULL,
    hora_entrega_programada TIME,
    fecha_entrega_efectiva TIMESTAMP,
    nombre_producto_snapshot VARCHAR(150),
    nombre_presentacion_snapshot VARCHAR(200),
    nombre_cliente_ocasional VARCHAR(150),
    estado_pedido VARCHAR(20) NOT NULL,
    moneda CHAR(3) NOT NULL DEFAULT 'BOB',
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario_snapshot NUMERIC(12,2) NOT NULL CHECK (precio_unitario_snapshot >= 0),
    costo_personalizacion NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (costo_personalizacion >= 0),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    fecha_carga_dw TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_fact_ventas_fecha ON dw.fact_ventas(sk_fecha_venta);
CREATE INDEX IF NOT EXISTS ix_fact_ventas_producto ON dw.fact_ventas(sk_producto);
CREATE INDEX IF NOT EXISTS ix_fact_ventas_cliente ON dw.fact_ventas(sk_cliente);
CREATE INDEX IF NOT EXISTS ix_fact_pedidos_fecha ON dw.fact_pedidos(sk_fecha_pedido);
CREATE INDEX IF NOT EXISTS ix_fact_pedidos_programada ON dw.fact_pedidos(sk_fecha_programada);
CREATE INDEX IF NOT EXISTS ix_fact_pedidos_producto ON dw.fact_pedidos(sk_producto);

-- Seguimiento de ejecuciones ETL. Las tablas de staging se incorporaran
-- al implementar el ETL en la siguiente etapa.
CREATE TABLE IF NOT EXISTS dw.etl_ejecucion (
    id_ejecucion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso VARCHAR(80) NOT NULL,
    inicio TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fin TIMESTAMPTZ,
    estado VARCHAR(20) NOT NULL DEFAULT 'INICIADO',
    filas_leidas INTEGER NOT NULL DEFAULT 0,
    filas_cargadas INTEGER NOT NULL DEFAULT 0,
    detalle TEXT
);

-- Calendario para las pruebas academicas (2024-2028).
INSERT INTO dw.dim_tiempo (
    sk_fecha, fecha, dia, mes, trimestre, anio, nombre_mes
)
SELECT
    TO_CHAR(f.fecha, 'YYYYMMDD')::INTEGER,
    f.fecha,
    EXTRACT(DAY FROM f.fecha)::SMALLINT,
    EXTRACT(MONTH FROM f.fecha)::SMALLINT,
    EXTRACT(QUARTER FROM f.fecha)::SMALLINT,
    EXTRACT(YEAR FROM f.fecha)::SMALLINT,
    TO_CHAR(f.fecha, 'TMMonth')
FROM (
    SELECT g::DATE AS fecha
    FROM generate_series(DATE '2024-01-01', DATE '2028-12-31', INTERVAL '1 day') AS g
) AS f
ON CONFLICT (sk_fecha) DO NOTHING;

COMMENT ON TABLE dw.fact_ventas IS
    'Importes registrados por detalle de venta. No equivalen por si solos a dinero cobrado.';
COMMENT ON TABLE dw.fact_pedidos IS
    'Pedidos por detalle, independiente de fact_ventas: no existe enlace automatico pedido-venta en OLTP.';
